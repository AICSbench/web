// Generates src/lib/types/export.ts from the export's JSON Schemas.
//   pnpm gen:types            reads tests/fixtures/export/schema/
//   SCHEMA_DIR=... pnpm gen:types
// CI regenerates it and fails when the committed file differs.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { format, resolveConfig } from 'prettier';

const schemaDir = resolve(process.env.SCHEMA_DIR ?? 'tests/fixtures/export/schema');
const out = resolve('src/lib/types/export.ts');

// File -> name of its top-level type. trials.schema.json has no title of its own.
const SCHEMAS: [string, string][] = [
	['export.schema.json', 'ExportInfo'],
	['meta.schema.json', 'Meta'],
	['pages.schema.json', 'Pages'],
	['trials.schema.json', 'Trials']
];

// Pydantic titles every property ("title": "Run Id"); json-schema-to-typescript would
// turn each into its own alias type. Keep titles only on the root and on $defs.
function stripTitles(node: unknown, keep: boolean): unknown {
	if (Array.isArray(node)) return node.map((item) => stripTitles(item, false));
	if (node === null || typeof node !== 'object') return node;
	const result: Record<string, unknown> = {};
	for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
		if (key === 'title' && !keep) continue;
		if (key === '$defs' && value && typeof value === 'object') {
			result[key] = Object.fromEntries(
				Object.entries(value).map(([name, def]) => [name, stripTitles(def, true)])
			);
		} else if (key === 'properties' && value && typeof value === 'object') {
			result[key] = Object.fromEntries(
				Object.entries(value).map(([name, def]) => [name, stripTitles(def, false)])
			);
		} else {
			result[key] = stripTitles(value, false);
		}
	}
	return result;
}

const parts: string[] = [];
const declared = new Set<string>();
for (const [file, name] of SCHEMAS) {
	const raw = JSON.parse(readFileSync(join(schemaDir, file), 'utf8')) as object;
	const schema = stripTitles({ ...raw, title: name }, true) as JSONSchema;
	const ts = await compile(schema, name, {
		bannerComment: '',
		additionalProperties: false,
		format: false,
		strictIndexSignatures: true,
		unreachableDefinitions: true
	});
	for (const match of ts.matchAll(/^export (?:interface|type) (\w+)/gm)) {
		if (declared.has(match[1])) throw new Error(`${file}: type ${match[1]} is declared twice`);
		declared.add(match[1]);
	}
	parts.push(`// From schema/${file}\n${ts}`);
}

const header = `// Generated by scripts/gen-types.ts from tests/fixtures/export/schema/*.schema.json.
// Do not edit by hand: run \`pnpm gen:types\`.
`;
const config = (await resolveConfig(out)) ?? {};
const text = await format(`${header}\n${parts.join('\n')}`, { ...config, filepath: out });
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, text);
console.log(`wrote ${out}`);
